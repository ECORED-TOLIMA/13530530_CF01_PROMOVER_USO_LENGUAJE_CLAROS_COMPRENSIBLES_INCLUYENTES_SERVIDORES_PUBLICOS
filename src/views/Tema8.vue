      h1 Metodologías en documentos elaborados y publicados
    p Publicar un documento institucional es solo el primer paso, su trabajo no termina solo en su divulgación. Es muy importante revisarlo y garantizar que la información sea fácil de comprender por las personas a quienes va dirigido. Un documento puede contener información correcta desde el punto de vista normativo y técnico, pero si presenta exceso de información, tecnicismos o instrucciones confusas puede presentar dificultades para ser entendido y termina alejando a las personas de la información.
    p Para solucionarlo, la Guía de lenguajes claros, comprensibles e incluyentes del SENA propone evaluar a la comprensión del contenido desde la experiencia real de las personas. Estas metodologías parten de una regla simple: Si se desea saber si un documento es claro solo se observa cómo lo usa y lo entiende quienes necesitan utilizarlo.
    p En este componente se desarrollan tres metodologías que facilitan este proceso; la entrevista estructurada, el semáforo de la comprensión y el laboratorio de simplicidad. Cada una de estas metodologías cumplen una función diferente, pero su objetivo en común es buscar el mismo resultado como, por ejemplo: identificar oportunidades de mejora para que la información sea clara, comprensible e incluyente. La Guía de lenguajes claros, comprensibles e incluyentes del SENA sugiere priorizar los documentos que están dirigidos a la ciudadanía, relacionados con el acceso a derechos y los que son ampliamente consultados o utilizados de manera frecuente en los canales institucionales. También recomienda identificar quienes son las personas destinatarias del documento, ya que sus características y necesidades son muy importantes porque orientan todo el proceso de evaluación.
