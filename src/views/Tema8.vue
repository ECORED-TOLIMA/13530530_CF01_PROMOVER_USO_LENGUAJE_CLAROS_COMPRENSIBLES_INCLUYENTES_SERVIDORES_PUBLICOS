      h2 8.5 Consideraciones de escritura en lenguajes claros, comprensibles e incluyentes
    p Antes de construir o revisar un documento, es importante recordar que escribir con claridad implica pensar primero en las personas que harán uso de la información. La Guía de lenguajes claros, comprensibles e incluyentes del SENA recomienda identificar primero quién recibirá el mensaje, que necesita conocer y cuál es el resultado que se espera después de la lectura.
    p Durante la elaboración de los documentos es preciso tener en cuenta las siguientes consideraciones:
    ul.lista-ul.mb-3
      li
