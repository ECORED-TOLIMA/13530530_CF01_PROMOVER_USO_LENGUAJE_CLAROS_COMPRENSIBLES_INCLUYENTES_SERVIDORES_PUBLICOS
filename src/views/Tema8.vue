      h2 8.4 Laboratorio de simplicidad
    p Es una metodología desarrollada por el Departamento Nacional de Planeación (DNP) que busca transformar documentos institucionales en textos más claros, comprensibles e incluyentes. A diferencia de las metodologías anteriores, esta estrategia no se centra en identificar dificultades, sino en construir soluciones a partir de las observaciones realizadas durante la revisión. Se trata de un trabajo colaborativo entre las entidades públicas y las personas que serán usuarias de la información, con el propósito de mejorar la comprensión de los documentos y fortalecer la comunicación con la ciudadanía.
    p Para desarrollar esta metodología, se parte de un documento previamente elaborado que es revisado de manera individual o colaborativa. Durante este proceso se identifican las dificultades de comprensión y se realizan los ajustes necesarios, procurando conservar el sentido del contenido, pero utilizando una forma de comunicación más cercana, clara y fácil de comprender.
    p Para la aplicación de esta metodología se recomienda:
    ul.lista-ul.mb-3
      li
        i.fas.fa-angle-right
        | Reemplazar palabras técnicas por expresiones de uso común, cuando sea posible.
    ul.lista-ul.mb-3
      li
        i.fas.fa-angle-right
        | Eliminar información repetitiva o innecesaria.
    ul.lista-ul.mb-3
      li
        i.fas.fa-angle-right
        | Dividir los párrafos demasiado extensos.
    ul.lista-ul.mb-3
      li
        i.fas.fa-angle-right
        | Organizar las ideas siguiendo una secuencia lógica.
    ul.lista-ul.mb-3
      li
        i.fas.fa-angle-right
        | Presentar primero la información más importante.
    ul.lista-ul.mb-3
      li
        i.fas.fa-angle-right
        | Verificar que las instrucciones indiquen claramente qué debe hacer la persona.
    p Una vez realizados los ajustes, es recomendable que el documento sea revisado por otras personas antes de su aprobación o publicación, con el fin de verificar que la información sea clara, comprensible y responda a las necesidades de la ciudadanía.
    p El laboratorio de simplicidad permite comprender que mejorar un documento no significa reducir información importante, sino presentarla de una manera más organizada, cercana y útil para facilitar el acceso, la comprensión y el uso de la información pública.
