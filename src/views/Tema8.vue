      h2 8.6 Guía de lenguajes claros, comprensibles e incluyentes (SENA)
    p Esta guía en su segunda versión se constituye como un referente metodológico para el conocimiento, elaboración y revisión de documentos y comunicaciones dirigidas a la ciudadanía. Si bien la guía es desarrollada por el Servicio Nacional de Aprendizaje SENA, sirve como sustento para todos los aprendices y servidores públicos para la ejecución de temas relacionados con el uso y aplicaciones de los lenguajes claros, comprensibles e incluyentes.
    p Se recomienda consultar la guía, adaptarla a los procesos de cada entidad pública del país, pues su consulta y utilización permite fortalecer las capacidades institucionales para identificar barreras de comprensión, poder organizar mejor la información, seleccionar el lenguaje y conceptos apropiados y construir mensajes que faciliten el acceso a los trámites, servicios, derechos y mecanismos de participación a todos los ciudadanos.
    p Finalmente, se espera que los aprendices incorporen estas orientaciones en sus prácticas cotidianas, llegando a la comprensión de que la comunicación clara y respetuosa no depende únicamente de escribir correctamente, sino de facilitar el acceso y reconocimiento de todas las personas y que a su vez ellas puedan encontrar, comprender y utilizar la información para el ejercicio y garantía de sus derechos en relación con las entidades públicas del país.
