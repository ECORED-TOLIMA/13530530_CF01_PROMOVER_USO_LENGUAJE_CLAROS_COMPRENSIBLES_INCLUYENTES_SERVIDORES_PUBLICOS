      h1 Lineamientos institucionales
    p Cuando una entidad comunica información pública, no empieza desde cero, de manera interna existen orientaciones que ayudan a cuidar la forma como se escriben los mensajes, se atiendes a la ciudadanía, se publican los contenidos y se responden las solicitudes. Estas orientaciones son los lineamientos institucionales.
    p Los lineamientos institucionales permiten que la información no dependa únicamente de la forma personal de quien redacta o atiente. Su función es ofrecer una ruta común para que la información sea clara, comprensible, respetuosa y útil. De esta manera, las personas pueden encontrar mensajes más ordenados y recibir una atención más cercana sin importar el canal que utilicen para acceder a la información.
    p En el acceso ciudadano, estos lineamientos son relevantes porque ayudan a evitar mensajes contradictorios, respuestas incompletas o información difícil de comprender. También permiten que las entidades mantengan un mismo estilo de comunicar la información, basada en el lenguaje claro, la atención respetuosa y el cumplimiento de la normativa vigente.
