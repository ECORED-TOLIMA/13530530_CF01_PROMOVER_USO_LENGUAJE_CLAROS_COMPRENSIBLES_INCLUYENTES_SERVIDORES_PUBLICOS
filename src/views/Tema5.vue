    p La comunicación pública está ligada al contexto ciudadano, cada mensaje institucional llega a personas que viven en contextos diferentes, tienen experiencias y comprenden la información desde sus propias condiciones sociales y culturales. Por eso, antes de diseñar una estrategia de acceso a la información pública, es necesario reconocer quiénes son las personas destinatarias, qué necesitan saber, cómo acceden a la información y qué barreras pueden enfrentar al momento de comprenderla o usarla.
