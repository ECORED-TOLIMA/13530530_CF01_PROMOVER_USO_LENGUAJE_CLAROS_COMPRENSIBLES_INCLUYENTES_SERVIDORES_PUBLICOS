    p Los ejercicios de poder se presentan cuando una entidad toma decisiones o realiza acciones que influyen en la forma como la ciudadanía accede a la información. En la comunicación pública, estos ejercicios pueden aparecer en situaciones cotidianas; exigir un documento, responder a una petición, negar una solicitud, publicar una convocatoria, explicar una norma o comunicar un cambio de un servicio.
    p Un ejercicio de poder puede ser adecuado cuando se realiza con claridad, trasparencia y respeto. Por ejemplo, una entidad puede negar una solicitud si no se cumple los requisitos, pero debe explicar la razón, indicar la norma en leguaje comprensible. En este sentido, la decisión institucional se mantiene, pero la comunicación permite que la persona entienda la situación y sepa la forma en la que debe de proceder; por el contrario, un ejercicio de poder puede convertirse en una barrera cuando la información se entrega de manera incompleta, confusa o distante.

