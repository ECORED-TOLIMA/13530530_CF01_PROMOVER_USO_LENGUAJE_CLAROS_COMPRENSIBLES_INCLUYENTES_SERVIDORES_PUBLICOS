      h1 Relaciones de poder
    p La comunicación entre Estado y ciudadanía no ocurre en condiciones iguales. Las entidades públicas cuentan con información, normas, procedimientos, sistemas y documentos que pueden afectar la vida de las personas. La ciudadanía, por su parte, necesita comprender esa información para realizar trámites, acceder a servicios, participar o ejercer sus derechos. Esta diferencia genera una relación de poder, porque quien posee, organiza y comunica la información tiene una responsabilidad frente a quien la necesita.
    p En la comunicación pública, las relaciones de poder se hacen visibles cuando la información se entrega de forma clara o confusa, cercana o distante, accesible o limitada. Un mensaje institucional puede abrir caminos para que la ciudadanía participe o también puede generar barreras si usa un lenguaje excesivamente técnico. Así que, reconocer las relaciones de poder permite comprender que la comunicación no es un acto neutral; la forma en la que se comunica puede facilitar o dificultar el acceso a la información.
