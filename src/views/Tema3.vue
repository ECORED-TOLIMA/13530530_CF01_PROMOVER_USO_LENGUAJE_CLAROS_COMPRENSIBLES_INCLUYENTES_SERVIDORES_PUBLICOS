      h2 3.1 Características, tipos, Estado y ciudadanía
    p Las relaciones de poder pueden entenderse como las formas en que una persona, grupo o institución influyen en las decisiones, acciones o posibilidades de otras personas. En el relacionamiento Estado-ciudadanía, estas relaciones se expresan en la capacidad que tienen las entidades para definir procedimientos, emitir respuestas, solicitar requisitos, publicar información y orientar la manera como la ciudadanía accede a tramites, servicios y derechos.
    p Esta relación no debe entenderse únicamente como algo negativo. El Estado necesita autoridad institucional para organizar servicios, tomar decesiones, aplicar normas y proteger el interés general. Sin embargo, esa autoridad debe ejercerse con responsabilidad, transparencia y claridad; porque cuando la información pública se comunica de manera comprensible, la relación de poder tendrá el equilibrio, puesto que la ciudadanía cuenta con los elementos para entender, decidir, preguntar y participar. Ahora bien, cuando la información se comunica de manera cerrada, técnica o poco accesible, la ciudadanía queda en desventaja porque se genera de esta manera una barrera entre la entidad y las personas.
