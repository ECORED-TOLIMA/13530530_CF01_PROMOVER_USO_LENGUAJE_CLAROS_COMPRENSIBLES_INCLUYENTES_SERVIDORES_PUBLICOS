      h1 Información pública
    p La información pública centra su enfoque en permitir que las personas puedan conocer decisiones, trámites, servicios programas, requisitos, derechos, deberes y hasta mecanismos de participación ciudadana. Pero es fundamental que, para el cumplimiento de su función, vaya más allá de estar publicada en una página web, carteleras, documento o algún canal institucional, la información debe ser clara, comprensible, accesible, oportuna y útil para quienes la necesiten. La información pública es una herramienta que permite el acercamiento y la conexión entre la ciudadanía y las entidades gubernamentales con el uso de esta información las personas pueden tomar decisiones, realizar solicitudes, participar en distintos procesos, ejercer control social o acceder a servicios.
